def truncate_text(text: Optional[str], max_chars: int = MAX_EPIC_CHARS) -> str:
    """Truncate text to maximum characters."""
    if not text:
        return ""
    text = text.strip()
    if len(text) <= max_chars:
        return text
    return text[:max_chars] + "..."


