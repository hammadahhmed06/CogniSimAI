def normalize_story(story: StoryOutput, index: int) -> Dict[str, Any]:
    """Convert StoryOutput to dictionary with defaults."""
    return {
        "title": story.title or f"Story {index + 1}",
        "persona": story.persona or "User",
        "user_value": story.user_value or "Delivers value to users",
        "acceptance_criteria": story.acceptance_criteria or ["Acceptance criteria to be defined"],
        "risks": story.risks or [],
    }


def compute_quality_score(
    stories: List[Dict[str, Any]],
    warnings: List[str],
    target_count: int,
) -> float:
    """Calculate quality score for generated stories."""
    if not stories:
        return 0.0
    
    score = 0.0
    
    # Story count match (30%)
    count_ratio = len(stories) / target_count if target_count > 0 else 1.0
    score += 0.3 * min(count_ratio, 1.0)
    
    # Acceptance criteria quality (40%)
    ac_scores = []
    for s in stories:
        ac = s.get("acceptance_criteria", [])
        if len(ac) >= 3:
            ac_scores.append(1.0)
        elif len(ac) >= 1:
            ac_scores.append(0.5)
        else:
            ac_scores.append(0.0)
    if ac_scores:
        score += 0.4 * (sum(ac_scores) / len(ac_scores))
    
    # Completeness (20%)
    complete_count = sum(
        1 for s in stories
        if len(s.get("user_value", "")) > 10 and len(s.get("persona", "")) > 0
    )
    score += 0.2 * (complete_count / len(stories))
    
    # Warning penalty (10%)
    warning_penalty = min(len(warnings) * 0.02, 0.1)
    score += 0.1 - warning_penalty
    
    return round(min(score, 1.0), 3)


