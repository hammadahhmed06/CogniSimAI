async def decompose_epic_from_jira(
    epic_key: str,
    integration_id: str,
    workspace_id: str,
    max_stories: int = 6,
    user_prompt: Optional[str] = None,
    push_to_jira: bool = False
) -> Dict[str, Any]:
    """
    Decompose an epic fetched directly from Jira and optionally push stories back.
    
    Args:
        epic_key: Jira epic key (e.g., 'PROJ-123')
        integration_id: Integration credentials ID
        workspace_id: Workspace ID
        max_stories: Maximum number of stories to generate
        user_prompt: Optional user guidance
        push_to_jira: Whether to push generated stories back to Jira
        
    Returns:
        Decomposition result with Jira keys if pushed
    """
    from app.services.jira import JiraOAuthManager, JiraAPIClient, JiraSyncService
    from app.core.config import settings
    
    # Get authenticated Jira client
    if not settings.JIRA_OAUTH_CLIENT_ID or not settings.JIRA_OAUTH_CLIENT_SECRET:
        return {
            "success": False,
            "error": "Jira OAuth not configured. Please set JIRA_OAUTH_CLIENT_ID and JIRA_OAUTH_CLIENT_SECRET."
        }
    
    oauth_manager = JiraOAuthManager(
        client_id=settings.JIRA_OAUTH_CLIENT_ID,
        client_secret=settings.JIRA_OAUTH_CLIENT_SECRET.get_secret_value()
    )
    access_token, cloud_id = await oauth_manager.ensure_valid_token(integration_id, workspace_id)
    jira_client = JiraAPIClient(access_token, cloud_id)
    
    # Fetch epic from Jira
    try:
        epic_issue = await jira_client.get_issue(
            epic_key,
            fields=["summary", "description", "project"]
        )
    except Exception as e:
        logger.error(f"Failed to fetch epic {epic_key} from Jira: {e}")
        return {
            "success": False,
            "error": f"Failed to fetch epic from Jira: {str(e)}"
        }
    
    # Extract epic description
    fields = epic_issue.get("fields", {})
    epic_title = fields.get("summary", "")
    epic_description_adf = fields.get("description", {})
    
    # Convert ADF to plain text
    epic_description = _extract_text_from_adf(epic_description_adf)
    full_epic_text = f"{epic_title}\n\n{epic_description}"
    
    logger.info(f"Fetched epic {epic_key} from Jira: {epic_title}")
    
    # Decompose the epic
    result = await decompose_epic(
        epic_description=full_epic_text,
        max_stories=max_stories,
        user_prompt=user_prompt
    )
    
    if not result.get("success"):
        return result
    
    # Push to Jira if requested
    if push_to_jira:
        stories = result.get("data", {}).get("stories", [])
        project_key = epic_issue["key"].split("-")[0]
        
        jira_results = []
        failed_stories = []
        
        for story in stories:
            try:
                # Create issue in Jira
                issue_data = {
                    "fields": {
                        "project": {"key": project_key},
                        "summary": story["title"],
                        "description": jira_client.convert_text_to_adf(
                            f"Persona: {story.get('persona', 'N/A')}\n\n"
                            f"Value: {story.get('user_value', 'N/A')}\n\n"
                            f"Acceptance Criteria:\n" + "\n".join([f"- {ac}" for ac in story.get("acceptance_criteria", [])])
                        ),
                        "issuetype": {"name": "Story"},
                        "customfield_10016": epic_key  # Epic link
                    }
                }
                
                created_issue = await jira_client.create_issue(issue_data)
                jira_results.append({
                    "title": story["title"],
                    "jira_key": created_issue["key"],
                    "jira_url": f"{jira_client.base_url}/browse/{created_issue['key']}"
                })
                logger.info(f"Created story in Jira: {created_issue['key']}")
                
            except Exception as e:
                logger.error(f"Failed to create story in Jira: {e}")
                failed_stories.append({
                    "title": story["title"],
                    "error": str(e)
                })
        
        result["jira_push_results"] = {
            "success": len(failed_stories) == 0,
            "created_count": len(jira_results),
            "failed_count": len(failed_stories),
            "created_stories": jira_results,
            "failed_stories": failed_stories
        }
    
    return result


def _extract_text_from_adf(adf: Dict) -> str:
    """
    Extract plain text from Atlassian Document Format.
    
    Args:
        adf: ADF document structure
        
    Returns:
        Plain text string
    """
    if not adf or not isinstance(adf, dict):
        return ""
    
    text_parts = []
    
    def extract_content(node):
        if isinstance(node, dict):
            node_type = node.get("type")
            
            if node_type == "text":
                text_parts.append(node.get("text", ""))
            elif node_type in ["paragraph", "heading", "listItem"]:
                if node.get("content"):
                    for child in node["content"]:
                        extract_content(child)
                    text_parts.append("\n")
            elif node.get("content"):
                for child in node["content"]:
                    extract_content(child)
        elif isinstance(node, list):
            for item in node:
                extract_content(item)
    
    if adf.get("content"):
        for content_node in adf["content"]:
            extract_content(content_node)
    
    return " ".join(text_parts).strip()


