@input_guardrail
async def validate_epic_input(
    ctx: RunContextWrapper[None],
    agent: Agent,
    input: str | list[TResponseInputItem],
) -> GuardrailFunctionOutput:
    """Validate that the input is a valid epic description."""
    # Extract text from input
    if isinstance(input, list):
        parts: List[str] = []
        for item in input:
            if isinstance(item, dict):
                content = item.get("content", "")
                if isinstance(content, str):
                    parts.append(content)
            elif isinstance(item, str):
                parts.append(item)
        text = " ".join(parts)
    else:
        text = str(input)
    
    text = text.strip()
    
    # Basic validation
    if not text:
        return GuardrailFunctionOutput(
            output_info={"reason": "Empty input"},
            tripwire_triggered=True,
        )
    
    if len(text) < 20:
        return GuardrailFunctionOutput(
            output_info={"reason": "Input too short - need at least 20 characters"},
            tripwire_triggered=True,
        )
    
    # Check for obvious non-epic content
    lower_text = text.lower()
    if any(word in lower_text for word in ["hello", "hi there", "what's up", "how are you"]):
        if len(text) < 50:  # Only trip if it's just a greeting
            return GuardrailFunctionOutput(
                output_info={"reason": "Input appears to be a greeting, not an epic"},
                tripwire_triggered=True,
            )
    
    return GuardrailFunctionOutput(
        output_info={"reason": "Valid epic input"},
        tripwire_triggered=False,
    )


