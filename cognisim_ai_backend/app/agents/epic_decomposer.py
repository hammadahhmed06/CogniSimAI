async def run_with_fallback(
    epic_description: str,
    target_stories: int,
) -> Tuple[Optional[StoriesOutput], List[str], str]:
    """Run the agent with Gemini."""
    warnings: List[str] = []
    
    if not gemini_client:
        raise RuntimeError("GEMINI_API_KEY is not configured")
    
    try:
        logger.info("Attempting generation with Gemini...")
        model = create_gemini_model()
        agent = create_story_generator_agent(model, target_stories)
        result = await Runner.run(agent, epic_description)
        if result.final_output and isinstance(result.final_output, StoriesOutput):
            logger.info(f"Gemini succeeded: {len(result.final_output.stories)} stories")
            return result.final_output, warnings, "gemini"
    except Exception as e:
        logger.error(f"Gemini generation failed: {e}")
        warnings.append(f"Gemini generation failed: {str(e)[:100]}")
    
    return None, warnings, "none"


async def decompose_epic_stream(
    epic_description: str,
    max_stories: int = 6,
    epic_id: Optional[str] = None,
    user_prompt: Optional[str] = None,
) -> AsyncGenerator[Dict[str, Any], None]:
    """Stream the epic decomposition pipeline.
    
    Yields progress events and final result.
    """
    # Validate inputs
    if not GEMINI_API_KEY:
        yield {"type": "error", "error": "GEMINI_API_KEY is not configured"}
        return
    
    if not epic_description or not epic_description.strip():
        yield {"type": "error", "error": "Epic description is required"}
        return
    
    # Bound story count
    target_stories = max(MIN_STORIES, min(max_stories, MAX_STORIES))
    
    # Prepare input
    epic_text = truncate_text(epic_description.strip(), MAX_EPIC_CHARS)
    
    # Add user prompt context if provided
    if user_prompt:
        epic_text = f"{epic_text}\n\nAdditional context: {truncate_text(user_prompt, 500)}"
    
    yield {"type": "progress", "stage": "init", "message": "Starting decomposition...", "percent": 5}
    
    # Fetch existing children for context
    existing_children = []
    if epic_id:
        existing_children, _ = _fetch_existing_children(epic_id)
        if existing_children:
            children_summary = _summarize_children(existing_children)
            epic_text = f"{epic_text}\n\nExisting stories (avoid duplicates):\n{children_summary}"
    
    yield {"type": "progress", "stage": "generating", "message": f"Generating {target_stories} stories...", "percent": 20}
    
    # Run the agent with fallback
    try:
        output, warnings, provider = await run_with_fallback(epic_text, target_stories)
    except Exception as e:
        logger.error(f"Agent execution failed: {e}")
        yield {"type": "error", "error": f"Agent execution failed: {str(e)}"}
        return
    
    yield {"type": "progress", "stage": "processing", "message": "Processing results...", "percent": 80}
    
    # Process results
    if not output or not output.stories:
        yield {
            "type": "result",
            "data": {
                "success": False,
                "data": None,
                "error": "No stories generated",
                "warnings": warnings,
                "quality_score": 0.0,
            }
        }
        return
    
    # Normalize stories
    final_stories = [
        normalize_story(story, idx)
        for idx, story in enumerate(output.stories)
    ]
    
    # Compute quality score
    quality_score = compute_quality_score(final_stories, warnings, target_stories)
    
    # Check story count
    if len(final_stories) != target_stories:
        warnings.append(f"Requested {target_stories} stories, got {len(final_stories)}")
    
    logger.info(
        "Pipeline complete: %d stories, quality=%.2f, provider=%s",
        len(final_stories), quality_score, provider
    )
    
    # Build final result
    result = {
        "success": len(final_stories) > 0,
        "data": {"stories": final_stories} if final_stories else None,
        "raw_output": output.model_dump_json() if output else None,
        "error": None if final_stories else "No stories generated",
        "warnings": warnings,
        "duplicate_matches": [],
        "quality_score": quality_score,
        "warnings_count": len(warnings),
        "analyst_insights": None,
        "review_feedback": None,
        "provider": provider,
    }
    
    yield {"type": "result", "data": result}
    yield {"type": "progress", "stage": "complete", "message": "Done", "percent": 100}


async def decompose_epic(
    epic_description: str,
    max_stories: int = 6,
    epic_id: Optional[str] = None,
    user_prompt: Optional[str] = None,
) -> Dict[str, Any]:
    """Synchronous wrapper for decompose_epic_stream."""
    final_result = {
        "success": False,
        "data": None,
        "raw_output": None,
        "error": "Unknown error",
    }
    
    async for event in decompose_epic_stream(epic_description, max_stories, epic_id, user_prompt):
        if event["type"] == "result":
            final_result = event["data"]
        elif event["type"] == "error":
            final_result = {
                "success": False,
                "data": None,
                "raw_output": None,
                "error": event["error"],
            }
    
    return final_result


async def regenerate_story(
    epic_description: str,
    epic_id: Optional[str],
    original_story: Dict[str, Any],
    feedback: str,
) -> Dict[str, Any]:
    """Regenerate a single story based on user feedback."""
    title = original_story.get("title", "Story")
    ac_list = original_story.get("acceptance_criteria", [])
    
    guidance = f"""REGENERATION REQUEST:
Original story: {title}
Current acceptance criteria: {', '.join(ac_list[:5])}

User feedback: {feedback}

Generate an improved version of this story addressing the feedback.
Generate exactly 1 story."""
    
    return await decompose_epic(
        epic_description=epic_description,
        max_stories=1,
        epic_id=epic_id,
        user_prompt=guidance,
    )


