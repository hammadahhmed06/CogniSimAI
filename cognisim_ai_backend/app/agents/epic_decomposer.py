def repair_json(raw: str) -> Optional[Dict[str, Any]]:
    """Attempt to parse/repair JSON from raw text (for backwards compatibility)."""
    if not raw:
        return None
    
    # Try direct parse
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        pass
    
    # Try to extract JSON from markdown fence
    import re
    fence_match = re.search(r'```(?:json)?\s*([\s\S]*?)```', raw)
    if fence_match:
        try:
            return json.loads(fence_match.group(1).strip())
        except json.JSONDecodeError:
            pass
    
    # Try to find JSON object
    brace_start = raw.find('{')
    if brace_start >= 0:
        try:
            return json.loads(raw[brace_start:])
        except json.JSONDecodeError:
            pass
    
    return None


