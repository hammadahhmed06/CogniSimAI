def _fetch_existing_children(epic_id: str) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """Fetch existing child issues for an epic (best effort)."""
    if not supabase:
        return [], []
    try:
        children_res = supabase.table("issues").select(
            "id,title,type,acceptance_criteria"
        ).eq("epic_id", epic_id).execute()
        children = getattr(children_res, 'data', []) or []
    except Exception as e:
        logger.debug(f"Failed to fetch children for epic {epic_id}: {e}")
        children = []
    return children, []


def _summarize_children(children: List[Dict[str, Any]]) -> str:
    """Summarize existing children for context."""
    if not children:
        return "(none)"
    out = []
    for c in children[:5]:
        title = (c.get('title') or '')[:80]
        out.append(f"- {title}")
    if len(children) > 5:
        out.append(f"... and {len(children) - 5} more")
    return "\n".join(out)


