def create_story_generator_agent(model, target_stories: int) -> Agent:
    """Create the story generator agent with structured output."""
    
    instructions = f"""You are an expert Agile Product Owner specializing in epic decomposition.

Your task is to decompose an epic description into EXACTLY {target_stories} user stories.

CRITICAL REQUIREMENTS:
1. Generate EXACTLY {target_stories} user stories - no more, no less
2. Each story must be independent and deliverable in a single sprint
3. Stories should follow the INVEST criteria (Independent, Negotiable, Valuable, Estimable, Small, Testable)
4. Each story needs 3-6 acceptance criteria in Given/When/Then format

OUTPUT FORMAT:
- title: Clear, action-oriented (5-12 words, e.g., "Implement user login with email verification")
- persona: Target user (e.g., "Registered User", "Admin", "Guest")
- user_value: Why this matters to the user/business
- acceptance_criteria: List of 3-6 testable criteria in Given/When/Then format
- risks: 0-2 potential implementation risks

IMPORTANT: You MUST generate exactly {target_stories} stories. Count them before responding.""" + STRICT_JSON_ONLY

    return Agent(
        name="Story Generator",
        instructions=instructions,
        model=model,
        output_type=StoriesOutput,
        model_settings=ModelSettings(
            temperature=0.3,
            max_tokens=4000,
        ),
        input_guardrails=[validate_epic_input],
    )


